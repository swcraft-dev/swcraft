"""The input/output oracle's XSD map: the committed data module is the derivation of the two licensed schemas.

:mod:`io_oracle_xsd_map_data` is generated by :mod:`io_oracle_xsd_map` and never hand-edited. The
schemas are never committed, so the oracle runs on the module everywhere; :class:`TestTheMapIsTheSchemas`
(the ``test-xsd`` suite, required under ``--require-autosar-xsd``) re-derives it from both schemas and
fails on any drift, the header's schema SHA-256 included. The other classes run on the committed module.
"""

from __future__ import annotations

import io_oracle_xsd_map
import io_oracle_xsd_map_data
import pytest
import xsd_support
from swcraft_tools.arxml_version import ArxmlVersion

_VERSIONS = {"4.2.2": ArxmlVersion.V4_2_2, "4.3.0": ArxmlVersion.V4_3_0}


def _both_schemas() -> dict[str, str]:
    """Return both licensed schemas, or skip (fail under ``--require-autosar-xsd``) naming both variables."""
    found = {release: xsd_support.licensed_schema(version) for release, version in _VERSIONS.items()}
    missing = [release for release, path in found.items() if path is None]
    if not missing:
        return {release: path for release, path in found.items() if path is not None}
    reason = (
        "the oracle's XSD map is derived from both licensed schemas, named by "
        + " and ".join(io_oracle_xsd_map.SCHEMA_VARIABLES.values())
        + ": "
        + " ".join(xsd_support.no_licensed_schema_reason(_VERSIONS[release]) for release in missing)
    )
    if xsd_support.REQUIRE_LICENSED_XSD:
        pytest.fail(f"--require-autosar-xsd was passed, but this test cannot run: {reason}")
    pytest.skip(reason)
    raise AssertionError("unreachable")  # pragma: no cover -- pytest.skip raises


class TestTheMapIsTheSchemas:
    def test_the_committed_module_is_the_derivation(self) -> None:
        derived = io_oracle_xsd_map.render(io_oracle_xsd_map.derive(_both_schemas()))
        committed = io_oracle_xsd_map.DATA_MODULE.read_text(encoding="utf-8")
        assert derived == committed, (
            "regenerate with `python packages/tools/tests/support/io_oracle_xsd_map.py` and commit it"
        )

    def test_no_pair_is_excluded(self) -> None:
        """No ``(parent, tag)`` pair has two classes or two wrapper verdicts."""
        assert io_oracle_xsd_map.derive(_both_schemas()).excluded == {}


class TestTheContextsTheOracleReads:
    """The pairs the oracle's number comparison and its empty-wrapper verdict meet, with their classes."""

    @pytest.mark.parametrize(
        ("pair", "klass"),
        [
            (("NUMERICAL-VALUE-SPECIFICATION", "VALUE"), "formula"),
            (("COMPU-NUMERATOR", "V"), "formula"),
            (("COMPU-DENOMINATOR", "V"), "formula"),
            (("COMPU-SCALE", "LOWER-LIMIT"), "formula"),
            (("COMPU-SCALE", "UPPER-LIMIT"), "formula"),
            (("PHYS-CONSTRS", "LOWER-LIMIT"), "formula"),
            (("INTERNAL-CONSTRS", "UPPER-LIMIT"), "formula"),
            (("SW-VALUES-PHYS", "V"), "numerical"),
            (("COMPU-CONST", "V"), "numerical"),
            (("SERVER-COM-SPEC", "QUEUE-LENGTH"), "positive-integer"),
            (("QUEUED-RECEIVER-COM-SPEC", "QUEUE-LENGTH"), "positive-integer"),
            (("SW-BASE-TYPE", "BASE-TYPE-SIZE"), "positive-integer"),
            (("DATA-CONSTR-RULE", "CONSTR-LEVEL"), "integer"),
            (("TIMING-EVENT", "PERIOD"), "double"),
        ],
    )
    def test_a_numeric_context_has_its_class(self, pair: tuple[str, str], klass: str) -> None:
        assert io_oracle_xsd_map_data.NUMERIC_CONTEXTS[pair] == klass

    @pytest.mark.parametrize(
        "pair",
        [
            ("TEXT-VALUE-SPECIFICATION", "VALUE"),
            ("COMPU-SCALE", "SHORT-LABEL"),
            ("COMPU-CONST", "VT"),
            ("SW-COMPONENT-DOCUMENTATION", "SW-VERSION"),
            ("SDG", "SD"),
        ],
    )
    def test_a_textual_context_is_no_number(self, pair: tuple[str, str]) -> None:
        assert pair not in io_oracle_xsd_map_data.NUMERIC_CONTEXTS

    def test_a_tag_alone_does_not_decide(self) -> None:
        """``VALUE`` is a formula under a numerical specification and text under a text specification."""
        numeric = io_oracle_xsd_map_data.NUMERIC_CONTEXTS
        assert numeric[("NUMERICAL-VALUE-SPECIFICATION", "VALUE")] == "formula"
        assert ("TEXT-VALUE-SPECIFICATION", "VALUE") not in numeric

    def test_every_class_is_one_the_oracle_parses(self) -> None:
        assert set(io_oracle_xsd_map_data.NUMERIC_CONTEXTS.values()) <= set(io_oracle_xsd_map.NUMBER_CLASSES)

    @pytest.mark.parametrize(
        "pair",
        [
            ("SWC-INTERNAL-BEHAVIOR", "DATA-TYPE-MAPPING-REFS"),
            ("SW-DATA-DEF-PROPS", "SW-DATA-DEF-PROPS-VARIANTS"),
            ("COMPU-INTERNAL-TO-PHYS", "COMPU-SCALES"),
            ("ADMIN-DATA", "SDGS"),
        ],
    )
    def test_a_wrapper_context(self, pair: tuple[str, str]) -> None:
        assert pair in io_oracle_xsd_map_data.WRAPPER_CONTEXTS

    @pytest.mark.parametrize(
        "pair",
        [
            ("APPLICATION-RECORD-DATA-TYPE", "SW-DATA-DEF-PROPS"),
            ("SW-DATA-DEF-PROPS-VARIANTS", "SW-DATA-DEF-PROPS-CONDITIONAL"),
            ("APPLICATION-PRIMITIVE-DATA-TYPE", "ADMIN-DATA"),
            ("COMPU-CONST", "VT"),
        ],
    )
    def test_an_object_or_a_leaf_is_no_wrapper(self, pair: tuple[str, str]) -> None:
        """A meta-class object with element-only content is no wrapper; nor is a simple-content leaf."""
        assert pair not in io_oracle_xsd_map_data.WRAPPER_CONTEXTS


#: A synthetic schema in the licensed schemas' idiom, small enough to state the whole map it gives:
#: a group reference, a choice, a mixed ``LIMIT`` with its ``mmt.qualifiedName``, a ``simpleContent``
#: integer, an anonymous element-only wrapper and a string leaf. *flip* is ``FLIP``'s type, so the two
#: releases can disagree on one pair's class; *extra* adds a pair one release alone declares.
_SYNTHETIC = """<?xml version="1.0" encoding="UTF-8"?>
<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" xmlns:AR="http://autosar.org/schema/r4.0"
           targetNamespace="http://autosar.org/schema/r4.0">
  <xs:simpleType name="INTEGER--SIMPLE"><xs:restriction base="xs:string"/></xs:simpleType>
  <xs:complexType name="INTEGER"><xs:simpleContent><xs:extension base="AR:INTEGER--SIMPLE"/></xs:simpleContent>
  </xs:complexType>
  <xs:complexType name="STRING"><xs:simpleContent><xs:extension base="xs:string"/></xs:simpleContent></xs:complexType>
  <xs:complexType name="LIMIT" mixed="true">
    <xs:annotation><xs:appinfo source="tags">mmt.qualifiedName="LimitValueVariationPoint"</xs:appinfo></xs:annotation>
  </xs:complexType>
  <xs:group name="LEVELS"><xs:sequence><xs:element name="LEVEL" type="AR:INTEGER"/></xs:sequence></xs:group>
  <xs:complexType name="OWNER">
    <xs:sequence>
      <xs:group ref="AR:LEVELS"/>
      <xs:choice><xs:element name="LOWER-LIMIT" type="AR:LIMIT"/></xs:choice>
      <xs:element name="ITEMS">
        <xs:complexType><xs:sequence><xs:element name="ITEM" type="AR:STRING"/></xs:sequence></xs:complexType>
      </xs:element>
      <xs:element name="FLIP" type="AR:{flip}"/>{extra}
    </xs:sequence>
  </xs:complexType>
  <xs:element name="OWNER" type="AR:OWNER"/>
</xs:schema>
"""


class TestTheGeneratorOnASyntheticSchema:
    """:func:`io_oracle_xsd_map.derive` on two small releases, witnessing the walker's rules in the fast gate.

    Group references and choices are walked, a mixed type is classed by its qualified name, a
    ``simpleContent`` type by its base, an anonymous element-only type is a wrapper, and a pair whose
    releases disagree on its class is excluded.
    """

    def test_the_derivation(self, tmp_path) -> None:
        paths = {}
        for release, flip, extra in (
            ("4.2.2", "INTEGER", ""),
            ("4.3.0", "STRING", '\n      <xs:element name="NEWER" type="AR:INTEGER"/>'),
        ):
            path = tmp_path / f"{release}.xsd"
            path.write_text(_SYNTHETIC.format(flip=flip, extra=extra), encoding="utf-8", newline="\n")
            paths[release] = str(path)

        derivation = io_oracle_xsd_map.derive(paths)

        assert dict(derivation.numeric) == {
            ("OWNER", "LEVEL"): "integer",
            ("OWNER", "LOWER-LIMIT"): "formula",
            ("OWNER", "NEWER"): "integer",
        }
        assert derivation.wrappers == frozenset({("OWNER", "ITEMS")})
        assert dict(derivation.excluded) == {("OWNER", "FLIP"): "classes None, integer"}
        older, newer = derivation.releases
        assert set(newer.pairs) - set(older.pairs) == {("OWNER", "NEWER")}
        rendered = io_oracle_xsd_map.render(derivation)
        assert "Excluded pairs (two verdicts across their declarations): 1." in rendered
        assert "0 pairs in R4.2.2 only, 1 in R4.3.0 only, 1 with a class that differs between the releases." in rendered
