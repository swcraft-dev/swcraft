def _document(path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _selected(path) -> dict[str, dict]:
    document = _document(path)
    return document["versions"][document["current_version"]]["needs"]


def _region_text() -> str:
    """The marked region of ``consumer/conf.py``: the start marker up to, not including, the end marker."""
    lines = (CONSUMER / "conf.py").read_text(encoding="utf-8").splitlines(keepends=True)
    starts = [index for index, line in enumerate(lines) if line.rstrip("\n") == REGION_START]
    ends = [index for index, line in enumerate(lines) if line.rstrip("\n") == REGION_END]
    assert len(starts) == 1 and len(ends) == 1 and starts[0] < ends[0], "conf.py holds one marked region"
    return "".join(lines[starts[0] : ends[0]])


def _region_declarations() -> dict[str, object]:
    """Each name the region assigns, with its literal value."""
    declared: dict[str, object] = {}
    for statement in ast.parse(_region_text()).body:
        assert isinstance(statement, ast.Assign) and len(statement.targets) == 1
        target = statement.targets[0]
        assert isinstance(target, ast.Name)
        declared[target.id] = ast.literal_eval(statement.value)
    return declared


#: The user guide page that gives the requirements team the region and the mapping lines.
