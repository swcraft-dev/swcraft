def _fenced_blocks(text: str, language: str) -> list[str]:
    """The content of every ``language`` fenced block of *text*, each ending in its last line's newline."""
    return re.findall(rf"^```{language}\n(.*?)^```$", text, flags=re.MULTILINE | re.DOTALL)


def _guide_region_block(text: str) -> str:
    """The one ``python`` block of *text* that opens with the region's start marker."""
    blocks = [block for block in _fenced_blocks(text, "python") if block.startswith(REGION_START + "\n")]
    assert len(blocks) == 1, f"the guide holds one block opening with the region's marker, found {len(blocks)}"
    return blocks[0]


#: The heading line, with its explicit anchor, of the guide section that publishes the architecture
#: (the import's own section has a ``sysreq`` mapping of its own).
PUBLISHING_HEADING = (
    "## Publishing the architecture to the requirements team"
    " { #publishing-the-architecture-to-the-requirements-team }\n"
)


def _publishing_section(text: str) -> str:
    """The guide's publishing section of *text*: from its heading to the next second-level heading."""
    start = text.index(PUBLISHING_HEADING) + len(PUBLISHING_HEADING)
    end = text.find("\n## ", start)
    return text[start:] if end == -1 else text[start : end + 1]


def _mapping_lines(text: str) -> str:
    """A mapping's text without its comments and blank lines, each kept line stripped of a trailing comment."""
    kept = (line.split("#", 1)[0].rstrip() for line in text.splitlines())
    return "".join(line + "\n" for line in kept if line)


def _mapping_without(path, ignored: tuple[str, ...], *dropped: str):
    """The mapping at *path* with *dropped* left out of its ``ignore`` line (all of them: the line removed)."""
    text = path.read_text(encoding="utf-8")
    line = f"ignore: [{', '.join(ignored)}]\n"
    assert text.count(line) == 1, "the mapping holds the ignore line as written"
    kept = [key for key in ignored if key not in dropped]
    return parse_mapping_text(text.replace(line, f"ignore: [{', '.join(kept)}]\n" if kept else ""))


def _team_mapping_without(*dropped: str):
    """The team's mapping with *dropped* left out of its ``ignore`` line (all six: the line removed)."""
    return _mapping_without(TEAM_MAPPING, TEAM_IGNORED, *dropped)


