class TestTheRefusals:
    def test_the_teams_build_without_the_ignore_line_is_refused_at_its_first_key_in_file_order(self):
        """Sphinx-Needs writes a need's keys sorted, so ``asil`` comes before the four link keys."""
        with pytest.raises(InterchangeError) as refused:
            parse_needs_text(TEAM_BUILD.read_text(encoding="utf-8"), _team_mapping_without(*TEAM_IGNORED))
        assert refused.value.pointer == f"/versions/{DELIVERY}/needs/SYS_001/asil"
        assert refused.value.sentence == TEAM_UNKNOWN_KEY

    @pytest.mark.parametrize("dropped", TEAM_IGNORED)
    def test_the_teams_build_is_refused_at_each_key_the_ignore_line_leaves_out(self, dropped):
        with pytest.raises(InterchangeError) as refused:
            parse_needs_text(TEAM_BUILD.read_text(encoding="utf-8"), _team_mapping_without(dropped))
        assert refused.value.pointer == f"/versions/{DELIVERY}/needs/SYS_001/{dropped}"
        assert refused.value.sentence == TEAM_UNKNOWN_KEY

    def test_the_teams_build_carries_swcraft_path_on_its_own_needs_which_the_ignore_line_names(self):
        """The declaration puts the field, empty, on every need of the team's own, so its next delivery holds it."""
        assert all(need[SWCRAFT_PATH] is None for need in _selected(TEAM_BUILD).values())

    def test_swcrafts_file_is_refused_at_swcraft_path_when_the_round_trip_mapping_leaves_it_out(self):
        with pytest.raises(InterchangeError) as refused:
            parse_needs_text(
                SWCRAFT_FILE.read_text(encoding="utf-8"),
                _mapping_without(ROUNDTRIP_MAPPING, ROUNDTRIP_IGNORED, SWCRAFT_PATH),
            )
        assert refused.value.pointer == f"/versions/{DELIVERY}/needs/AR_001/{SWCRAFT_PATH}"
        assert refused.value.sentence.startswith("unknown key: map it under 'fields' in --mapping")

    @pytest.mark.parametrize("key", ["title", "content"])
    def test_swcrafts_file_with_a_blank_title_or_description_is_refused_by_the_round_trip(self, key):
        """A blank title or description, accepted by the model and the team's build, is refused by the import's reader.

        A limit, not a refusal of the export: the reader says ``must not be blank`` whatever the mapping says."""
        document = json.loads(SWCRAFT_FILE.read_text(encoding="utf-8"))
        document["versions"][DELIVERY]["needs"]["AS_001"][key] = ""
        with pytest.raises(InterchangeError) as refused:
            parse_needs_text(json.dumps(document), read_mapping(ROUNDTRIP_MAPPING))
        assert refused.value.pointer == f"/versions/{DELIVERY}/needs/AS_001/{key}"
        assert refused.value.sentence == "must not be blank"

    def test_swcrafts_file_without_a_mapping_is_refused_at_the_first_architecture_requirement_type(self):
        with pytest.raises(InterchangeError) as refused:
            read_needs_file(SWCRAFT_FILE)
        assert refused.value.pointer == f"/versions/{DELIVERY}/needs/AR_001/type"
        assert refused.value.sentence == "type 'arch_req' is not SWCraft's; map it under 'types' in --mapping"

    def test_the_committed_warning_log_is_empty(self):
        """Both ``-W`` builds of 9.2.0 wrote no warning; a non-empty log would have failed them."""
        assert WARNING_LOG.read_bytes() == b""

    def test_the_evidence_was_taken_on_the_file_the_writer_builds_today(self):
        """The builds' stamp names today's ``needs.json`` bytes: a writer change without a rebuild fails here."""
        assert BUILT_FROM.read_text(encoding="utf-8") == (
            f"{hashlib.sha256(SWCRAFT_FILE.read_bytes()).hexdigest()}  swcraft/needs.json\n"
        )
