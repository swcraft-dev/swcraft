class TestTheGuide:
    def test_the_guides_conf_py_block_is_the_marked_region_byte_for_byte(self):
        """What the team copies from the guide is what Sphinx-Needs 9.2.0 built with ``-W``."""
        assert _guide_region_block(GUIDE.read_text(encoding="utf-8")) == _region_text()

    def test_the_guide_gives_the_teams_mapping_as_committed(self):
        """The publishing section's ``sysreq`` mapping is the one the return trip reads, comments aside."""
        section = _publishing_section(GUIDE.read_text(encoding="utf-8"))
        blocks = [block for block in _fenced_blocks(section, "yaml") if "sysreq" in block]
        assert blocks == [_mapping_lines(TEAM_MAPPING.read_text(encoding="utf-8"))]

    def test_the_guides_ignore_line_with_swcrafts_own_names_is_the_round_trips(self):
        """With SWCraft's own names the three link keys and ``swcraft_path`` the import does not read are ignored."""
        line = f"ignore: [{', '.join(ROUNDTRIP_IGNORED)}]\n"
        assert line in _fenced_blocks(GUIDE.read_text(encoding="utf-8"), "yaml")
        assert line in ROUNDTRIP_MAPPING.read_text(encoding="utf-8")

    def test_a_guide_block_one_byte_off_the_region_is_not_equal(self):
        guide = GUIDE.read_text(encoding="utf-8")
        changed = guide.replace('"allow_dead_links": True,', '"allow_dead_links": False,', 1)
        assert changed != guide
        assert _guide_region_block(changed) != _region_text()

    def test_a_guide_without_the_block_or_with_two_is_refused(self):
        guide = GUIDE.read_text(encoding="utf-8")
        block = _guide_region_block(guide)
        with pytest.raises(AssertionError, match="found 0"):
            _guide_region_block(guide.replace(REGION_START, "# another comment", 1))
        with pytest.raises(AssertionError, match="found 2"):
            _guide_region_block(guide + f"\n```python\n{block}```\n")


