class TestTheBracketIdsRoundTrip:
    """The whole loop for ids holding ``[``, run here and not only committed.

    The team's build (the next delivery, holding the two ``needimport``
    requirements) is imported into the vector's model without them; the import
    writes their files with the parent read whole. Once the architect links them,
    ``needs.json`` publishes both links whole, as the committed file the team's
    ``-W`` build resolved does. Does not reach: Sphinx itself.
    """

    def test_import_link_and_publish_again(self, tmp_path: Path) -> None:
        project = tmp_path / "project"
        shutil.copytree(MANIFEST.parent, project, ignore=shutil.ignore_patterns("dist"))
        requirements = project / "model" / "requirements"
        for need_id in BRACKET_IDS:
            (requirements / f"{need_id}.yaml").unlink()
        linked = {
            project / "model" / "hardware" / "BrakeEcu.yaml": "- SYS_REQ[12]@1\n- '[[SYS_REQ_14]]@1'\n",
            project / "model" / COMPONENT_FILE: "  - SYS_REQ[13]@1\n",
        }
        for path, line in linked.items():
            text = path.read_text(encoding="utf-8")
            assert text.count(line) == 1, path
            path.write_text(text.replace(line, ""), encoding="utf-8", newline="\n")

        result = run_captured(
            [
                sys.executable,
                "-m",
                "swcraft_tools.cli",
                "import",
                "requirements",
                "--source",
                str(TEAM_BUILD),
                "--mapping",
                str(TEAM_MAPPING),
                "--project",
                str(project / "swcraft.yaml"),
            ],
            project,
            env={**os.environ, "PYTHONUTF8": "1"},
        )
        assert result.returncode == 0, result.stderr
        committed = MANIFEST.parent / "model" / "requirements"
