def _target_url() -> str:
    """The committed ``needs_external_needs`` entry's ``target_url``: a template over the need."""
    (entry,) = _region_declarations()["needs_external_needs"]
    return entry["target_url"]


def _filled(path: str) -> str:
    """The template filled with *path* as Jinja's ``urlencode`` renders a string: ``/`` kept, the rest quoted."""
    return _target_url().replace(PATH_PLACEHOLDER, urllib.parse.quote(path, safe="/"))


class TestTheLinkOpensTheElementsFile:
    def test_every_need_names_a_model_file_that_declares_it(self):
        """Model-root-relative, POSIX, never absolute; a port's or a runnable's is its component's file."""
        model_root = OUTPUT / "model" / "model"
        for need_id, need in _selected(SWCRAFT_FILE).items():
            path = need[SWCRAFT_PATH]
            assert not path.startswith("/") and ":" not in path and "\\" not in path, (need_id, path)
            assert (model_root / path).is_file(), (need_id, path)
            declared = (model_root / path).read_text(encoding="utf-8")
            identity = need["title"].split(".", 1)[0] if need["type"] == "arch_element" else need_id
            assert re.search(rf"^(id|name): {re.escape(identity)}$", declared, flags=re.MULTILINE), (need_id, path)
        assert _selected(SWCRAFT_FILE)["PORT-BrakeCtrl-pBrakeReq"][SWCRAFT_PATH] == COMPONENT_FILE
        assert _selected(SWCRAFT_FILE)["RUN-BrakeCtrl-BrakeRun"][SWCRAFT_PATH] == COMPONENT_FILE

    def test_the_committed_target_url_is_a_template_over_the_path(self):
        assert _target_url().count(PATH_PLACEHOLDER) == 1
        assert _target_url().startswith("https://git.example.com/")

    def test_each_link_of_the_rendered_page_is_the_template_filled_with_its_needs_path(self):
        """Read off the page 9.2.0 rendered, not computed: the click opens the element's file."""
        needs = _selected(SWCRAFT_FILE)
        links = _SWCRAFT_LINK.findall(TEAM_PAGE.read_text(encoding="utf-8"))
        assert {need_id for _, need_id in links} == set(needs)
        for href, need_id in links:
            assert href == _filled(needs[need_id][SWCRAFT_PATH]), need_id
        # The group directory's `#` and `[[` are escaped, so the whole path reaches the address.
        assert (
            "https://git.example.com/our-org/architecture/src/branch/main/model/swc/brake%23%5B%5B1%5D%5D/BrakeCtrl.yaml",
            "PORT-BrakeCtrl-pBrakeReq",
        ) in links

    def test_the_href_check_fails_when_two_needs_paths_are_swapped(self):
        """With two needs' ``swcraft_path`` exchanged the check above fails: it reads each ``href``'s need."""
        needs = {need_id: dict(need) for need_id, need in _selected(SWCRAFT_FILE).items()}
        first, second = needs["AR_001"], needs["SWC-BrakeCtrl"]
        first[SWCRAFT_PATH], second[SWCRAFT_PATH] = second[SWCRAFT_PATH], first[SWCRAFT_PATH]
        links = _SWCRAFT_LINK.findall(TEAM_PAGE.read_text(encoding="utf-8"))
        mismatched = {need_id for href, need_id in links if href != _filled(needs[need_id][SWCRAFT_PATH])}
        assert mismatched == {"AR_001", "SWC-BrakeCtrl"}


