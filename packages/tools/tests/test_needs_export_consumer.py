"""The consumer vector: Sphinx-Needs 9.2.0 reads SWCraft's ``needs.json``, and the team's build comes back.

The independent oracle is committed under
``packages/tools/tests/fixtures/contracts/requirements-interchange/output/``: a small SWCraft project,
the ``needs.json`` ``swcraft generate needs`` wrote for it, a requirements team's
Sphinx project loading that file with ``needs_external_needs``, and what
``sphinx-build -W -b needs`` and ``-W -b html`` of Sphinx-Needs 9.2.0 left (an empty
warning log and the team's own ``needs.json``). **No test runs Sphinx**: it is not a
dependency of SWCraft at any stage, so these tests hold the code to the committed
evidence by bytes.

What they hold: SWCraft's output equals the committed file; every type, field and
link key it uses is declared in the consumer's marked region; the team's build
carries the back links the file's links promise, confirmed and unconfirmed apart;
the team's build is read by the import's reader through the team's mapping, and
refused without the mapping's ``ignore`` line; SWCraft's own file is read back
through the round-trip mapping, and refused without one.

What they do not reach: whether Sphinx-Needs still builds the consumer project --
the evidence is regenerated by hand when the output or the pinned release moves
(the directory's ``README.md``); any release but 9.2.0; ``needimport``; and what
the HTML page shows beyond the links SWCraft's needs carry --
``TestTheLinkOpensTheElementsFile`` holds each of those, in the committed page, to
the entry's ``target_url`` template filled with the need's ``swcraft_path``.
``TestTheGuide`` holds the guide's ``conf.py`` block to the marked region byte for
byte, and its mapping block to the team's mapping; it does not reach the guide's
prose around them.
"""

