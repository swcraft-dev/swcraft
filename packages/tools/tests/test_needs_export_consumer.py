class TestSwcraftsFile:
    def test_the_committed_file_is_what_the_writer_builds_for_the_model(self):
        project = require_project(str(MANIFEST))
        built = build_needs_json(project.resolved_model_root, project.name)
        assert built.encode("utf-8") == SWCRAFT_FILE.read_bytes()

    def test_the_consumer_loads_the_same_bytes(self):
        assert (CONSUMER / "swcraft" / "needs.json").read_bytes() == SWCRAFT_FILE.read_bytes()

    def test_the_file_names_the_delivery_and_echoes_no_incoming_requirement(self):
        document = _document(SWCRAFT_FILE)
        assert document["current_version"] == DELIVERY
        assert list(document["versions"]) == [DELIVERY]
        assert not {"SYS_001", "SYS_002", "SYS_003", "CUST_001"} & set(_selected(SWCRAFT_FILE))

    def test_every_type_field_and_link_the_file_uses_is_declared_in_the_marked_region(self):
        """An undeclared type refuses the need and an undeclared key is dropped with a warning (9.2.0)."""
        declared = _region_declarations()
        types = {entry["directive"] for entry in declared["needs_types"]}
        keys = KEPT_CORE_FIELDS | set(declared["needs_fields"]) | set(declared["needs_links"])
        for need_id, need in _selected(SWCRAFT_FILE).items():
            assert need["type"] in types, need_id
            assert set(need) <= keys, (need_id, set(need) - keys)

    def test_the_region_allows_dead_links_on_the_unconfirmed_types_alone(self):
        links = _region_declarations()["needs_links"]
        assert {name for name, spec in links.items() if spec.get("allow_dead_links")} == {
            "satisfies_unconfirmed",
            "derived_from_unconfirmed",
        }

    def test_the_region_reads_swcraft_path_as_text_and_the_vectors_path_holds_a_dynamic_function_start(self):
        """By default 9.2.0 reads a ``[[`` in the field as a dynamic function; the region switches that off."""
        assert _region_declarations()["needs_fields"][SWCRAFT_PATH]["parse_dynamic_functions"] is False
        assert "[[" in COMPONENT_FILE and "#" in COMPONENT_FILE
        assert COMPONENT_FILE in {need[SWCRAFT_PATH] for need in _selected(SWCRAFT_FILE).values()}


