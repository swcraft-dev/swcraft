class TestTheTeamsBuild:
    def test_the_team_holds_every_non_stub_incoming_requirement_and_none_of_swcrafts_needs(self):
        """The default builder filter keeps external needs out of the team's own file."""
        assert list(_selected(TEAM_BUILD)) == ["SYS_001", "SYS_002", "SYS_003", *BRACKET_IDS]
        assert all(not need["is_external"] for need in _selected(TEAM_BUILD).values())

    def test_the_needimported_requirements_keep_their_bracket_ids_and_link_whole(self):
        """``needimport`` declares an id holding ``[`` as it is, and the team's own ``parent`` reaches it whole."""
        team = _selected(TEAM_BUILD)
        assert [team[need_id]["is_import"] for need_id in BRACKET_IDS] == [True, True, True]
        assert team["SYS_REQ[13]"]["parent"] == ["SYS_REQ[12]"]
        assert team["SYS_REQ[12]"]["parent_back"] == ["SYS_REQ[13]"]

    def test_the_region_reads_every_link_whole_and_swcrafts_file_links_the_bracket_ids(self):
        """The region turns off ``parse_conditions`` (``[12]``) and ``parse_dynamic_functions`` (a leading ``[[``)."""
        region = _region_text()
        assert region.count('"parse_conditions": False') == len(LINK_TYPES)
        assert region.count('"parse_conditions": False, "parse_dynamic_functions": False') == len(LINK_TYPES)
        linked = {
            target
            for need in _selected(SWCRAFT_FILE).values()
            for link_type in LINK_TYPES
            for target in need.get(link_type, [])
        }
        assert set(BRACKET_IDS) <= linked

    def test_each_team_requirement_carries_the_back_links_confirmed_and_unconfirmed_apart(self):
        team = _selected(TEAM_BUILD)
        for need_id, expected in EXPECTED_BACK_LINKS.items():
            assert {key: team[need_id][key] for key in expected} == expected, need_id

    def test_every_link_of_swcrafts_file_to_a_team_requirement_is_a_back_link_there(self):
        """Derived from the file, not restated: each link reaches the team's need under its own type."""
        team = _selected(TEAM_BUILD)
        promised = 0
        for source_id, need in _selected(SWCRAFT_FILE).items():
            for link_type in LINK_TYPES:
                for target in need.get(link_type, []):
                    if target in team:
                        assert source_id in team[target][f"{link_type}_back"], (source_id, link_type, target)
                        promised += 1
        assert promised == 9

    def test_the_stub_is_named_only_by_an_unconfirmed_link(self):
        """``CUST_001``, which the team never delivered, is a dead link the region allows."""
        naming = {
            (need_id, link_type)
            for need_id, need in _selected(SWCRAFT_FILE).items()
            for link_type in LINK_TYPES
            if "CUST_001" in need.get(link_type, [])
        }
        assert naming == {("AR_001", "derived_from_unconfirmed")}
        assert "CUST_001" not in _selected(TEAM_BUILD)

    def test_the_team_build_names_the_release_that_built_it(self):
        """The evidence is 9.2.0's; a rebuild under another release must move this line on purpose."""
        creator = _document(TEAM_BUILD)["versions"][DELIVERY]["creator"]
        assert creator == {"program": "sphinx_needs", "version": "9.2.0"}


