"""The SWCraft model validator: port compatibility and cross-layer consistency checks.

Each check returns a result from :mod:`.results`: :class:`CompatibilityResult` for a port
pair, :class:`ConsistencyResult` for a consistency check. A :class:`ConsistencyResult` carries
the verdict (``consistent``), the findings' prose (``issues``, derived from ``records``) and
the same findings as :class:`ConsistencyIssue` records, each with a stable rule identifier,
the message and the model subjects (:mod:`swcraft_tools.diagnostics`) it is about, so a
consumer can act on a finding by rule and address without matching message text.

:data:`CONSISTENCY_RULES` (:mod:`.rules`) names every rule a check can emit; every error rule
maps onto an editing-protocol error code, and no warning rule does. :data:`WARNING_RULES`
(:mod:`.results`) names the warning rules; every other rule is an error (:func:`severity_of`).
``consistent``, ``issues`` and ``records`` hold the error half of the deduplicated records,
``warnings`` the rest, each in emission order.

:func:`check_cross_layer_consistency` (:mod:`.composer`) validates a whole model in a fixed
order; each ``check_*`` function can also be called alone, with a
:class:`~.model_view.ModelView` or a model root. This ``__init__`` re-exports every
submodule's public names except ``model_view.py``'s, and no private name, listed in ``__all__``.
"""

