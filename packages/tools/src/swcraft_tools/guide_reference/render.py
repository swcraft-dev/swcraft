"""The shared Markdown emitters for the generated guide reference.

Nothing here sorts or reads a clock, a host path or the product version, and :func:`document` joins
its blocks in the order given, so a re-render is byte-identical on another machine.

**Two escapes.** A source string is prose written as Markdown, emitted verbatim except the table cell
separator (:func:`cell`) and a ``<`` outside a backtick code span (:func:`escape_markup`, applied by
:func:`paragraph` and :func:`cell`).

**What this module does not reach:**

* ``&`` is not escaped: a source string spelling ``&lt;`` renders as ``<``.
* :func:`heading`, :func:`link`, :func:`code` and :func:`purpose_comment` do not escape; a caller
  handing one a *source* string routes it through :func:`escape_markup` itself.
* The code-span scan is CommonMark's backtick rule only: it knows nothing of fenced blocks, indented
  code or HTML blocks; the one fenced block, the schema pages', never passes through these escapes.
  An unbalanced backtick opens no span.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterable, Sequence
from typing import Any

__all__ = [
    "ANCHOR_PATTERN",
    "CUT_LEVELS",
    "GENERATED_COMMENT",
    "GENERATED_NOTICE",
    "REGENERATE_COMMAND",
    "anchored_code",
    "cell",
    "code",
    "document",
    "escape_markup",
    "heading",
    "link",
    "literal",
    "paragraph",
    "purpose_comment",
    "table",
]

#: The command that re-renders every page, named in :data:`GENERATED_COMMENT` so a developer finding a
#: stale sentence knows what to run.
REGENERATE_COMMAND = "python scripts/dev.py docs-reference"

#: The line every generated page's source opens with: an HTML comment for the developer, which MkDocs
#: does not render.
GENERATED_COMMENT = f"<!-- generated by {REGENERATE_COMMAND}; do not edit by hand -->"

#: The one line every rendered page shows under its title, for the reader. It names no date: the bytes
#: must not depend on the clock.
GENERATED_NOTICE = (
    "*This page is generated from SWCraft's own definitions, and describes the version you have installed.*"
)


def literal(value: Any) -> str:
    """One declared value in the spelling a reader would type.

    A non-empty string is written bare (``kind: core``); everything else goes through ``json.dumps``.
    The empty string needs the quotes: bare, it would read as a missing value.
    """
    return value if isinstance(value, str) and value else json.dumps(value)


#: The heading levels the guide's corpus cuts a page at: a heading there is a section an agent
#: addresses by ``<page>#<anchor>``, so :func:`heading` requires an explicit anchor.
CUT_LEVELS = frozenset({2, 3})

#: An authoring comment's terminator; a purpose holding it would close its comment early.
_COMMENT_END = "-->"


def purpose_comment(text: str) -> str:
    """The authoring comment ``<!-- purpose: text -->`` that says when the section above it helps.

    *text* must be one non-empty, stripped line without ``-->``; anything else raises ``ValueError``.
    **Does not check:** the length cap (``guide_search.PURPOSE_CAP_CHARACTERS``).
    """
    if not text or text != text.strip() or "\n" in text or "\r" in text or _COMMENT_END in text:
        raise ValueError(f"purpose {text!r} is not one non-empty line without {_COMMENT_END!r}")
    return f"<!-- purpose: {text} -->"


def heading(level: int, text: str, *, purpose: str, anchor: str | None = None) -> str:
    """One ATX heading, its explicit anchor, and the purpose comment under it.

    Levels 1-6. *anchor* is rendered as ``attr_list``'s ``{ #anchor }``, fixing the heading's HTML id
    (and the site's URL and the corpus's section id) so a reworded heading moves neither. It is
    required at :data:`CUT_LEVELS` and must match :data:`ANCHOR_PATTERN`; callers derive it as the id
    MkDocs' ``toc`` would mint. The purpose comment is a block directly under the heading, where the
    corpus producer looks for it.
    """
    if not 1 <= level <= 6:
        raise ValueError(f"heading level {level} is outside Markdown's 1-6")
    line = f"{'#' * level} {text}"
    if anchor is None:
        if level in CUT_LEVELS:
            raise ValueError(f"a level-{level} heading needs an explicit anchor: {text!r}")
    else:
        if ANCHOR_PATTERN.fullmatch(anchor) is None:
            raise ValueError(f"anchor {anchor!r} is outside {ANCHOR_PATTERN.pattern}")
        line = f"{line} {{ #{anchor} }}"
    return f"{line}\n\n{purpose_comment(purpose)}"


#: A run of backticks: CommonMark opens a code span on one and closes it on the next run of the same
#: length.
_BACKTICK_RUN = re.compile(r"`+")


def escape_markup(text: str) -> str:
    """*text* with every ``<`` outside a backtick code span escaped to ``&lt;``.

    An angle-bracketed placeholder would otherwise be read as a tag and vanish from the built site.
    A code span is copied through untouched; an unterminated backtick run opens no span, so the rest
    is escaped as prose.
    """
    out: list[str] = []
    position = 0
    while position < len(text):
        opener = _BACKTICK_RUN.search(text, position)
        if opener is None:
            out.append(text[position:].replace("<", "&lt;"))
            break
        out.append(text[position : opener.start()].replace("<", "&lt;"))
        run = opener.group()
        closer = re.compile(rf"(?<!`){re.escape(run)}(?!`)").search(text, opener.end())
        if closer is None:
            out.append(run)
            position = opener.end()
            continue
        out.append(text[opener.start() : closer.end()])
        position = closer.end()
    return "".join(out)


def paragraph(text: str) -> str:
    """One paragraph, whitespace-normalized, with ``<`` escaped outside code spans (:func:`escape_markup`)."""
    return escape_markup(" ".join(text.split()))


def code(text: str) -> str:
    """One inline code span."""
    return f"`{text}`"


#: The spelling an anchor may take: letters, digits, ``.``, ``_`` and ``-``, one to 128 of them. It
#: needs no escape in a URL fragment, and ``toc``'s slugify strips dots, so a dotted anchor cannot
#: collide with a heading's id. The bound matches the editor's ``ANCHOR_PATTERN``
#: (``vscode_extension/src/helpLinks.ts``), so every anchor is one a finding's link can name.
ANCHOR_PATTERN = re.compile(r"[A-Za-z0-9._-]{1,128}")


def anchored_code(text: str, anchor: str) -> str:
    """One inline code span carrying the HTML id *anchor*, through ``attr_list``.

    Rendered ``` `text`{ #anchor } ```, which ``attr_list`` turns into ``<code id="anchor">``, inside a
    table cell too. An anchor outside :data:`ANCHOR_PATTERN` raises ``ValueError``.
    """
    if ANCHOR_PATTERN.fullmatch(anchor) is None:
        raise ValueError(f"anchor {anchor!r} is outside {ANCHOR_PATTERN.pattern}")
    return f"{code(text)}{{ #{anchor} }}"


def link(text: str, target: str) -> str:
    """One inline link. *target* is relative to the page being rendered."""
    return f"[{text}]({target})"


def cell(text: str) -> str:
    """One table cell's text: pipes escaped, hard line breaks collapsed, ``<`` escaped outside code spans.

    An unescaped ``|`` would start a column and a newline end the row, silently reshaping the table.
    Other Markdown is left alone.
    """
    return escape_markup(" ".join(text.split()).replace("|", r"\|"))


def table(headers: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    """One pipe table, in the row order it is handed.

    A row whose width differs from *headers* raises ``ValueError``: it would render as content rather
    than as the caller bug it is.
    """
    materialized = [list(row) for row in rows]
    for index, row in enumerate(materialized):
        if len(row) != len(headers):
            raise ValueError(f"row {index} has {len(row)} cells, the table has {len(headers)} columns: {row}")
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines.extend("| " + " | ".join(cell(value) for value in row) + " |" for row in materialized)
    return "\n".join(lines)


def document(*blocks: str) -> str:
    """The page text: the non-empty blocks, one blank line apart, one trailing newline.

    Empty blocks are dropped, so a caller can pass ``"" if absent else block``.
    """
    return "\n\n".join(block for block in blocks if block) + "\n"
