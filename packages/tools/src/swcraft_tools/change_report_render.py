def _requirement_json(row: RequirementRow) -> dict[str, Any]:
    return {
        "requirement": row.requirement,
        "holder": row.holder,
        "change": row.change,
        "oldVersion": row.old_version,
        "newVersion": row.new_version,
        "messages": list(row.messages),
    }


def _resource_json(row: ResourceRow) -> dict[str, Any]:
    return {
        "name": row.name,
        "kind": row.kind,
        "budget": row.budget.exact,
        "before": row.before,
        "after": row.after,
        "change": row.change,
        "status": row.status,
    }


def render_json(report: ChangeReport) -> str:
    """``change-report.json``: deterministic, ``indent=2``, ``allow_nan=False``, newline-terminated.

    ``changes`` is ``swcraft diff --format json``'s ``layers`` object verbatim, so its non-finite floats are
    already spelled ``"NaN"``/``"Infinity"``; every other figure is a string or an integer, and
    ``allow_nan=False`` keeps a hole in that loud.
    """
    diagrams: list[dict[str, Any]] | None = None
    if report.diagrams is not None:
        diagrams = [
            {
                "composition": overview.composition,
                "before": None if overview.before_svg is None else overview_file(overview.stem, "before"),
                "after": overview_file(overview.stem, "after"),
            }
            for overview in report.diagrams
        ]
    document = {
        "schemaVersion": SCHEMA_VERSION,
        "kind": "change-report",
        "revisions": {"old": report.old_label, "new": report.new_label},
        "verdict": {
            "errors": report.introduced_errors,
            "warnings": report.introduced_warnings,
            "changes": report.change_count,
            "elements": report.element_count,
            "compositions": len(report.compositions),
            "existingErrors": report.existing_errors,
            "existingWarnings": report.existing_warnings,
        },
        "changes": json.loads(format_diff_json(report.diff))["layers"],
        "requirements": [_requirement_json(row) for row in report.requirement_rows],
        "findings": [
            {"rule": finding.rule, "severity": finding.severity, "message": finding.message}
            for finding in report.findings
        ],
        "resources": [_resource_json(row) for row in report.resources],
        "consumers": [
            {
                "interface": group.interface,
                "change": group.change,
                "dependents": [{"layer": dependent.layer, "name": dependent.name} for dependent in group.dependents],
            }
            for group in report.consumers
        ],
        "arxml": {
            "compared": report.arxml.compared,
            "reason": report.arxml.reason,
            "elements": [
                {"path": element.path, "type": element.type, "change": element.change}
                for element in report.arxml.elements
            ],
        },
        "diagrams": diagrams,
    }
    return json.dumps(document, indent=2, allow_nan=False) + "\n"


def report_files(report: ChangeReport) -> list[tuple[str, str]]:
    """Every file of the report as ``(file name, text)``.

    The Markdown, the pull request's Markdown, the JSON, then each picture drawn.

    The names are flat, for the one report directory; an added composition has no before picture.
    """
    files = [
        (MARKDOWN_FILE, render_markdown(report)),
        (PR_MARKDOWN_FILE, render_markdown(report, diagrams=False)),
        (JSON_FILE, render_json(report)),
    ]
    for overview in report.diagrams or ():
        if overview.before_svg is not None:
            files.append((overview_file(overview.stem, "before"), overview.before_svg))
        files.append((overview_file(overview.stem, "after"), overview.after_svg))
    return files
