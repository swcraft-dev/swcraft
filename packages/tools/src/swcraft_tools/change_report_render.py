"""The change report's documents, rendered from a :class:`~swcraft_tools.change_report.ChangeReport`.

:func:`render_markdown` writes ``change-report.md``: the title and meta, the verdict, seven sections and the
footer, in that order, each section printing one sentence when it has nothing to say, so every report has one
fixed shape. ``change-report-pr.md`` is the same Markdown without its Diagrams section, the text a pull request
carries. :func:`render_json` writes ``change-report.json``; :func:`report_files` lists every file of one report
with its text, the overview pictures included. No timestamp and no location: the same change gives the same
bytes, and nothing names where the project is stored.

**Safely Markdown**: a model text in a table cell has ``|`` escaped, a line break turned into a space and
``<``/``&`` spelled as entities, so the document holds no raw HTML; a name is set in a code span, a
double-backtick one when it holds a backtick. The headings and the rows' shape are fixed.

**What it does not reach.** It is handed a report and the differ's answer, never a model element: every fact is
:mod:`swcraft_tools.change_report`'s, and ``changes`` in the JSON is the ``swcraft diff --format json``
document's ``layers`` object verbatim, snake_case keys and all. The pictures are referenced by relative path,
flat beside the Markdown, which VS Code's preview renders and a pull request comment does not, so
``change-report-pr.md`` names no picture, no legend and no "not drawn" note.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any
from urllib.parse import quote

from swcraft_tools.change_report import ChangeReport, ConsumerGroup, RequirementRow, ResourceRow
from swcraft_tools.differ import format_diff_json
from swcraft_tools.markdown_cells import cell_text, code_span, table

__all__ = [
    "JSON_FILE",
    "MARKDOWN_FILE",
    "PR_MARKDOWN_FILE",
    "REPORT_DIRECTORY",
    "SCHEMA_VERSION",
    "is_report_file",
    "overview_file",
    "render_json",
    "render_markdown",
    "report_files",
]

#: The report's directory below ``dist_root``, and the documents' file names beside the pictures in it.
REPORT_DIRECTORY = "change-report"
MARKDOWN_FILE = "change-report.md"
JSON_FILE = "change-report.json"
#: ``change-report.md`` without its Diagrams section: the text for a pull request.
PR_MARKDOWN_FILE = "change-report-pr.md"

#: ``change-report.json``'s major version; a consumer rejects one it does not know.
SCHEMA_VERSION = 1

_MISSING_FIGURE = "—"
_SEPARATOR = " · "
_ARROW = "→"

_LEGEND = "Legend: added — green outline; removed — red dashed outline; lines — green added, red removed, blue both."
_FOOTER = (
    "Generated by `swcraft change-report` from the model at two revisions; every line is computed from the "
    "model, nothing is written by AI. The manifest at the working tree is used for both revisions."
)


def overview_file(stem: str, side: str) -> str:
    """``overview-<stem>-before.svg`` / ``overview-<stem>-after.svg``: one picture's file name."""
    return f"overview-{stem}-{side}.svg"


def is_report_file(name: str) -> bool:
    """Whether *name* is one of the files a change report writes, compared by ``str.casefold()``.

    The three documents and any ``overview-*-before.svg`` / ``overview-*-after.svg``.
    """
    folded = name.casefold()
    if folded in (MARKDOWN_FILE, PR_MARKDOWN_FILE, JSON_FILE):
        return True
    return folded.startswith("overview-") and (folded.endswith("-before.svg") or folded.endswith("-after.svg"))


def remove_earlier_report_files(directory: Path, produced: Sequence[str]) -> None:
    """Remove the report files an earlier run left in *directory* that this run did not produce.

    Call it after the new set is written, so a failed write leaves the earlier set whole. Only a regular file
    directly in *directory* whose name :func:`is_report_file` recognises is removed, never a link or a directory;
    names are compared by ``str.casefold()``, so on a case-insensitive filesystem a picture renamed by case alone
    is the file just written and stays.
    """
    kept = {name.casefold() for name in produced}
    for entry in sorted(directory.iterdir(), key=lambda path: path.as_posix()):
        if (
            is_report_file(entry.name)
            and entry.name.casefold() not in kept
            and entry.is_file()
            and not entry.is_symlink()
        ):
            entry.unlink()


