def _already(report: ChangeReport) -> str:
    """`` (N already in the model)``: the findings the model had before the change too.

    So "0 warning(s) introduced" never reads as "the model has no warning". Only the non-zero kinds are
    named; warnings alone are the bare count, which the "warning(s) introduced" before it names.
    """
    errors, warnings = report.existing_errors, report.existing_warnings
    if not errors and not warnings:
        return ""
    if not errors:
        return f" ({warnings} already in the model)"
    parts = [f"{errors} error{'' if errors == 1 else 's'}"]
    if warnings:
        parts.append(f"{warnings} warning{'' if warnings == 1 else 's'}")
    return f" ({', '.join(parts)} already in the model)"


def _verdict(report: ChangeReport) -> str:
    if report.is_empty:
        return "**No change to the model.**"
    return (
        f"**{report.introduced_errors} error(s){_SEPARATOR}{report.introduced_warnings} warning(s) introduced"
        f"{_already(report)}{_SEPARATOR}{report.change_count} change(s) in {report.element_count} element(s)"
        f"{_SEPARATOR}{len(report.compositions)} composition(s).**"
    )


def _what_changed(report: ChangeReport) -> list[str]:
    if report.is_empty:
        return ["No change to the model."]
    rows = []
    for row in report.changed_elements:
        change = row.change
        if row.rename_of is not None:
            change += f" — possibly a rename of {code_span(row.rename_of)}"
        if row.leaves:
            change += " — " + "; ".join(cell_text(leaf) for leaf in row.leaves)
        rows.append((code_span(row.element), cell_text(row.kind), change))
    return table(("Element", "Kind", "Change"), rows)


def _version(version: str | None) -> str:
    return "no version stated" if version is None else cell_text(f"@{version}")


def _requirement_change(row: RequirementRow) -> str:
    if row.change == "gained":
        return f"gained, {_version(row.new_version)}"
    if row.change == "lost":
        return f"lost, {_version(row.old_version)}"
    if row.change == "re-confirmed":
        return f"re-confirmed, {_version(row.old_version)} {_ARROW} {_version(row.new_version)}"
    return "needs confirmation: " + " ".join(cell_text(message) for message in row.messages)


def _requirements(report: ChangeReport) -> list[str]:
    if not report.requirement_rows:
        return ["No requirement link was gained, lost or re-confirmed, and none needs confirmation."]
    rows = [
        (
            code_span(row.requirement),
            _MISSING_FIGURE if row.holder is None else cell_text(row.holder),
            _requirement_change(row),
        )
        for row in report.requirement_rows
    ]
    return table(("Requirement", "Holder", "Change"), rows)


def _findings(report: ChangeReport) -> list[str]:
    if not report.findings:
        return ["The change introduces no finding; findings the model already had are not listed."]
    rows = [(cell_text(finding.message), finding.severity) for finding in report.findings]
    return ["Findings the model already had are not listed.", "", *table(("Finding", "Severity"), rows)]


def _figure(value: str | None) -> str:
    return _MISSING_FIGURE if value is None else cell_text(value)


def _resources(report: ChangeReport) -> list[str]:
    if not report.resources:
        return ["The model declares no core or memory."]
    rows = [
        (
            code_span(row.name),
            cell_text(row.budget.shown),
            _figure(row.before),
            _figure(row.after),
            _figure(row.change),
            _figure(row.status),
        )
        for row in report.resources
    ]
    return table(("Resource", "Budget", "Before", "After", "Change", "Status"), rows)


def _dependent_groups(group: ConsumerGroup) -> list[tuple[str, list[str]]]:
    """The dependents grouped by their layer's label, in the order each label is first met, names in walk order."""
    grouped: dict[str, list[str]] = {}
    for dependent in group.dependents:
        grouped.setdefault(dependent.label, []).append(dependent.name)
    return list(grouped.items())


def _consumers(report: ChangeReport) -> list[str]:
    if not report.consumers:
        return ["No interface was changed or removed."]
    lines = [
        "Every element that depends on an interface the change changed (read at the new revision) or removed "
        "(read at the old revision)."
    ]
    for group in report.consumers:
        lines += ["", f"### {code_span(group.interface)} ({group.change})", ""]
        groups = _dependent_groups(group)
        if not groups:
            lines.append("Nothing depends on it.")
            continue
        lines += table(
            ("Layer", "Dependents"),
            [(cell_text(label), ", ".join(code_span(name) for name in names)) for label, names in groups],
        )
    return lines


def _arxml(report: ChangeReport) -> list[str]:
    comparison = report.arxml
    if not comparison.compared:
        return [comparison.reason or "Not compared."]
    if not comparison.elements:
        return ["No ARXML element changed."]
    rows = [(code_span(element.path), cell_text(element.type), element.change) for element in comparison.elements]
    return table(("Element", "Type", "Change"), rows)


def _link(file_name: str) -> str:
    """A picture's file name as a link destination, percent-encoded.

    A space or a ``#`` in a name the schema accepts then cannot end the destination or start a fragment (the
    file keeps its own name).
    """
    return quote(file_name)


def _alt(text: str) -> str:
    return text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def _diagrams(report: ChangeReport) -> list[str]:
    if report.diagrams is None:
        return [report.diagram_note or "Not drawn."]
    if not report.diagrams:
        return ["No composition holds a change."]
    lines = [_LEGEND]
    for overview in report.diagrams:
        name = " ".join(overview.composition.splitlines())
        lines += ["", f"### {code_span(overview.composition)}", "", f"Before — {cell_text(report.old_label)}:", ""]
        if overview.before_svg is None:
            lines.append(f"Did not exist at {cell_text(report.old_label)}.")
        else:
            lines.append(f"![{_alt(name)} before]({_link(overview_file(overview.stem, 'before'))})")
        lines += [
            "",
            f"After — {cell_text(report.new_label)}:",
            "",
            f"![{_alt(name)} after]({_link(overview_file(overview.stem, 'after'))})",
        ]
    return lines


def render_markdown(report: ChangeReport, *, diagrams: bool = True) -> str:
    """``change-report.md``: title and meta, the verdict, then the seven sections and the footer.

    With ``diagrams=False`` it is ``change-report-pr.md``: the same text without the Diagrams section, the only
    part that names a picture, the legend or a "not drawn" note.
    """
    sections = [
        ("Verdict", [_verdict(report)]),
        ("What changed", _what_changed(report)),
        ("Requirements", _requirements(report)),
        ("Findings", _findings(report)),
        ("Resources", _resources(report)),
        ("Interface consumers", _consumers(report)),
        ("ARXML", _arxml(report)),
    ]
    if diagrams:
        sections.append(("Diagrams", _diagrams(report)))
    lines = [
        "# Change Report",
        "",
        f"{cell_text(report.project_name)}{_SEPARATOR}{cell_text(report.new_label)}"
        f" against {cell_text(report.old_label)}",
    ]
    for title, body in sections:
        lines += ["", f"## {title}", "", *body]
    lines += ["", "---", "", _FOOTER]
    return "\n".join(lines) + "\n"


