"""The guide's tool reference: its content oracle, its drift gate and its cross-checks.

``docs/guide/reference/tools.md`` is generated by :mod:`swcraft_mcp.tool_reference`
and committed. This module is that page's whole gate: the sibling gate in
``packages/tools/tests/test_guide_reference_drift.py`` exempts it by name, because
``swcraft_tools`` may not import ``swcraft_mcp``.

Four independent questions:

- **the content oracle**: every registered tool and every argument is on the
  page, derived from the registration, with the count cross-checked against the
  ``@mcp.tool()`` decorations in ``server.py``;
- **the drift gate**, in both directions, the orphan direction spanning both
  generators: the tools-side half exempts exactly this page, and this half
  asserts that exemption is exactly what this generator produces, so neither
  can drift into covering nothing;
- **the cross-check against the frozen decision table**: the rendered set is the
  live retained tools plus the protocol's four request shapes and the added
  questions;
- **the vocabulary gate over the live descriptions**, from
  ``guide_fixtures.FORBIDDEN_VOCABULARY``: a description is also what the
  assistant is told.

Every gate is also shown to fire against a mutated copy.

**What this module does not reach**: whether a tool's purpose sentence is true
of what it does, whether the page reads well, whether a link resolves
(``mkdocs build --strict``), and the narrative pages beside ``reference/``.
"""

