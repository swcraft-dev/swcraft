def test_the_generator_imports_no_model_structure() -> None:
    """The generator imports none of ``swcraft_tools.schema``, ``snapshot`` or ``reader``.

    It keeps ``packages/mcp/`` a pass-through for the model contract's consumer
    inventory. An AST scan of this one file: it does not reach the rest of the
    package, nor what an imported module imports in turn.
    """
    tree = ast.parse(GENERATOR_PATH.read_text(encoding="utf-8"))
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("swcraft_tools"):
            imported.update((node.module or "").split(".")[1:])
            imported.update(alias.name for alias in node.names)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith("swcraft_tools"):
                    imported.update(alias.name.split(".")[1:])
    offenders = sorted(imported & set(MODEL_STRUCTURE_MODULES))
    assert not offenders, f"{GENERATOR_PATH.name} imports model structure: {offenders}"


