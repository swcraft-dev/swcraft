def _sections(text: str) -> list[str]:
    """The tool names the page carries as level-2 headings, in page order."""
    return re.findall(r"^## `([^`]+)` \{ #[^ }]+ \}$", text, re.MULTILINE)


def _section_body(text: str, name: str) -> str:
    """One tool's section: everything from its heading to the next one, or the end."""
    parts = re.split(r"^## ", text, flags=re.MULTILINE)
    for part in parts[1:]:
        if part.startswith(f"`{name}` {{ #"):
            return part
    raise AssertionError(f"{name} has no section on the page")


# ---------------------------------------------------------------------------
# The rules, as functions
# ---------------------------------------------------------------------------
#
# Each gate and its ``TestTheGatesFire`` case call the same function, the gate
# on the real surface (the ``None`` default) and the case on a mutation, so a
# fire-test cannot pass against an emptied generator.


def argument_rows(body: str) -> list[str]:
    """The argument names one tool section's table declares, in table order."""
    return re.findall(r"^\| `([^`]+)` \|", body, re.MULTILINE)


def undocumented_arguments(page_text: str | None = None, tools: Sequence[Any] | None = None) -> list[str]:
    """``tool.argument`` for every registered argument the page's own section does not list."""
    tools = registered_tools() if tools is None else tools
    page_text = tools_page(tools=tools) if page_text is None else page_text
    missing: list[str] = []
    for tool in tools:
        rendered = set(argument_rows(_section_body(page_text, tool.name)))
        missing.extend(
            f"{tool.name}.{argument}"
            for argument in (tool.parameters or {}).get("properties", {})
            if argument not in rendered
        )
    return missing


def stale_pages(artifacts: Mapping[str, str] | None = None, guide_dir: Path | None = None) -> list[str]:
    """Generated pages whose committed bytes are not the bytes the generator renders."""
    artifacts = all_artifacts() if artifacts is None else artifacts
    guide_dir = GUIDE_DIR if guide_dir is None else guide_dir
    stale = []
    for relative, text in artifacts.items():
        committed = guide_dir / relative
        if not committed.is_file() or committed.read_bytes() != text.encode("utf-8"):
            stale.append(relative)
    return stale


def unnavigated_pages(artifacts: Mapping[str, str] | None = None, navigated: Iterable[str] | None = None) -> list[str]:
    """Generated pages no ``mkdocs.yml`` navigation row reaches."""
    artifacts = all_artifacts() if artifacts is None else artifacts
    navigated = navigation_paths() if navigated is None else navigated
    return sorted(set(artifacts) - set(navigated))


def navigation_paths(config_text: str | None = None) -> list[str]:
    """The document paths ``mkdocs.yml``'s ``Reference`` section names (the narrative rows are another gate's)."""
    config_text = MKDOCS_YML.read_text(encoding="utf-8") if config_text is None else config_text
    config = yaml.safe_load(config_text)
    section = next(entry for entry in config["nav"] if isinstance(entry, dict) and "Reference" in entry)
    return nav_paths(section["Reference"])


def removed_names_in(text: str, removed: Iterable[str]) -> list[str]:
    """Every removed tool name *text* spells as a word."""
    return [name for name in removed if re.search(rf"\b{re.escape(name)}\b", text)]


class TestTheContentOracle:
    """Every registered tool, and every argument of one, derived from the registration."""

    def test_every_registered_tool_has_a_section_in_registration_order(
        self, page: str, live_tools: tuple[Any, ...]
    ) -> None:
        assert _sections(page) == [tool.name for tool in live_tools]

    def test_every_registered_tool_is_in_the_summary_table(self, page: str, live_tools: tuple[Any, ...]) -> None:
        for tool in live_tools:
            assert f"[`{tool.name}`](#{tool.name.lower()})" in page, f"{tool.name} is missing from the summary table"

    def test_the_section_count_is_the_registration_count_read_off_the_server(self, page: str) -> None:
        """The page's tools are the decorated functions read off ``server.py``'s AST, never a remembered count."""
        tree = ast.parse(SERVER_PATH.read_text(encoding="utf-8"))
        decorated = [
            node.name
            for node in ast.walk(tree)
            if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef)
            and any(
                isinstance(target := (d.func if isinstance(d, ast.Call) else d), ast.Attribute)
                and target.attr == "tool"
                for d in node.decorator_list
            )
        ]
        assert sorted(_sections(page)) == sorted(decorated)

    def test_every_argument_of_every_tool_is_in_its_own_section(self, page: str, live_tools: tuple[Any, ...]) -> None:
        missing = undocumented_arguments(page, live_tools)
        assert not missing, f"arguments missing from their tool's table: {missing}"

    def test_the_argument_oracle_reads_a_non_empty_corpus(self, live_tools: tuple[Any, ...]) -> None:
        """A per-argument gate over a surface with no arguments passes vacuously."""
        declared = [
            f"{tool.name}.{argument}"
            for tool in live_tools
            for argument in (tool.parameters or {}).get("properties", {})
        ]
        assert declared, "no registered tool declares an argument, so the case above proves nothing"

    def test_a_tool_with_no_arguments_says_so_rather_than_rendering_an_empty_table(
        self, page: str, live_tools: tuple[Any, ...]
    ) -> None:
        argumentless = [tool for tool in live_tools if not (tool.parameters or {}).get("properties")]
        assert argumentless, "no registered tool is argumentless, so this case proves nothing"
        for tool in argumentless:
            body = _section_body(page, tool.name)
            assert "This tool takes no arguments." in body
            assert "| Argument |" not in body

    def test_requiredness_is_rendered_from_the_schema(self, page: str, live_tools: tuple[Any, ...]) -> None:
        """Every required argument reads "required" and every optional one does not."""
        seen_required = seen_optional = False
        for tool in live_tools:
            schema = tool.parameters or {}
            required = set(schema.get("required") or ())
            body = _section_body(page, tool.name)
            for argument in schema.get("properties", {}):
                (row,) = [line for line in body.splitlines() if line.startswith(f"| `{argument}` |")]
                if argument in required:
                    seen_required = True
                    assert row.endswith("| required |"), row
                else:
                    seen_optional = True
                    assert "optional" in row, row
        assert seen_required and seen_optional, "the surface exercises only one of the two states"

    def test_a_declared_default_is_shown(self, page: str, live_tools: tuple[Any, ...]) -> None:
        """A reader who leaves an argument out is told what they get instead."""
        defaults = [
            (tool.name, argument, fragment["default"])
            for tool in live_tools
            for argument, fragment in (tool.parameters or {}).get("properties", {}).items()
            if fragment.get("default") is not None
        ]
        assert defaults, "no registered argument declares a non-null default, so this case proves nothing"
        for name, argument, default in defaults:
            (row,) = [line for line in _section_body(page, name).splitlines() if line.startswith(f"| `{argument}` |")]
            # Case-insensitively: the page writes `false`, not Python's `False`.
            assert "when you leave it out" in row and str(default).lower() in row.lower(), row

    def test_the_purpose_is_the_descriptions_first_paragraph(self, live_tools: tuple[Any, ...]) -> None:
        """The purpose is the first paragraph; the escaping is composed, not restated.

        ``render.paragraph`` escapes ``<`` outside code spans, and its own suite
        tests that. No registered description reaches the escape today; the
        composition keeps the case from failing on the next one that does.
        """
        for tool in live_tools:
            first_paragraph = " ".join((tool.description or "").strip().split("\n\n", 1)[0].split())
            assert tool_reference.purpose(tool) == escape_markup(first_paragraph)

    def test_every_description_opens_with_verb_object_and_use_when(self, live_tools: tuple[Any, ...]) -> None:
        """Every live description opens ``<Verb> <object> — use when <situation>``.

        What a model choosing a tool reads first. What this does not reach:
        whether the verb and the situation are the right ones, only the shape.
        """
        assert live_tools, "no registered tool, so this case proves nothing"
        shape = re.compile(r"^[A-Z][a-z]+\b,? \S.*? — use when \S")
        offenders = [
            tool.name
            for tool in live_tools
            if not shape.match(" ".join((tool.description or "").strip().split("\n\n", 1)[0].split()))
        ]
        assert not offenders, f"descriptions not opening '<Verb> <object> — use when': {offenders}"


class TestTheReadOperationsAreParameters:
    """A member path, ``derived`` and ``join`` are arguments of ``read``, never tools.

    What it does not reach: whether the sentences are true of the engine, which
    ``test_protocol_discover_read.py``'s ``TestTheThreeOperationsTogether`` drives.
    """

    def test_the_read_section_carries_both_new_arguments(self, page: str) -> None:
        body = _section_body(page, "read")
        for argument in ("members", "derived", "join"):
            assert any(line.startswith(f"| `{argument}` |") for line in body.splitlines()), argument

    def test_the_published_argument_descriptions_name_their_preconditions_and_bounds(
        self, live_tools: tuple[Any, ...]
    ) -> None:
        """Off the argument descriptions (FastMCP publishes each ``Args`` entry as its argument's), by token.

        Each argument names the values its precondition, bound and refusals are stated in: the identifiers
        a host acts on, never a sentence.
        """
        (read,) = [tool for tool in live_tools if tool.name == "read"]
        properties = (read.parameters or {})["properties"]

        def described(argument: str) -> str:
            return " ".join(properties[argument].get("description", "").split())

        assert "`through`" in described("members")
        for argument in ("derived", "join"):
            # The precondition: an explicit row form, `index` or `count`.
            assert '`form: "index"`' in described(argument), argument
            assert '`"count"`' in described(argument), argument
            assert "`schema-violation`" in described(argument), argument
        assert "`reads.derived`" in described("derived")
        assert "`unknown-field`" in described("derived")
        for token in ("`reads.join.max_entries`", "`reads.join.row_ceiling`", "`over-budget`", "`where`"):
            assert token in described("join"), token


class TestTheCrossCheckAgainstTheDecisionTable:
    """The rendered set against the frozen decision table: two statements of one surface."""

    def test_the_rendered_set_is_the_retained_tools_and_the_protocol_shapes(self, page: str, table: dict) -> None:
        expected = set(live_retained(table)) | set(PROTOCOL_TOOLS) | set(ADDED_QUESTIONS)
        rendered = set(_sections(page))
        assert rendered == expected, (
            f"unexpected on the page: {sorted(rendered - expected)}; missing: {sorted(expected - rendered)} — "
            f"{REGENERATE}"
        )

    def test_the_page_opens_with_the_four_protocol_tools(self, page: str) -> None:
        """The intro sentence says "the first four are the whole editing surface"; this is what makes it true."""
        assert _sections(page)[:4] == list(PROTOCOL_TOOLS)

    def test_no_removed_tool_name_reaches_the_page(self, page: str, table: dict) -> None:
        """The generator's prose names no removed tool, not even in the past tense the docs scan admits."""
        removed = sorted(removed_tools(table))
        assert removed, "the decision table records no removed tool, so this gate reads an empty list"
        named = removed_names_in(page, removed)
        assert not named, f"the tool reference names removed tools: {named}"


